export type Config = z.infer<typeof schema> & {
  isDemo: boolean;
  isProduction: boolean;
  corsOrigins: string[];
  databasePath: string;
  reportsDir: string;
  assetsDir: string;
  privateFilesDir: string;
  /** EXERCISE_MEDIA_DIR resolved: the exercise clips, posters and their manifest.json. */
  exerciseMediaDir: string;
  websiteDir: string;
  dashboardDir: string;
  jobsEnabled: boolean;
  /** The open preview is effective: BIOPTIME_MODE=demo and OPEN_PREVIEW=1 (any other mode with OPEN_PREVIEW=1 refuses
   *  to start). Every workspace opens without signing in; api/auth/openPreview.ts. */
  openPreview: boolean;
  /** Google OAuth client IDs by platform (only those set). */
  googleClientIds: { web?: string; ios?: string; android?: string };
  /** Every audience an Apple identity token may name: the app's bundle IDs and the Services ID (web and Android). */
  appleAudiences: string[];
};

export function loadConfig(overrides: Partial<Record<keyof z.infer<typeof schema>, string>> = {}): Config {
  const fromFile = { ...loadDotEnv(path.join(PLATFORM_ROOT, '.env')), ...loadDotEnv(path.join(API_ROOT, '.env')) };
  const merged: Record<string, string | undefined> = { ...fromFile, ...process.env, ...overrides };
  const parsed = schema.safeParse(merged);
  if (!parsed.success) {
    throw new Error('Invalid configuration: ' + parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; '));
  }
  const c = parsed.data;
  const isProduction = c.BIOPTIME_MODE === 'production';
  // the open preview signs anyone with the link in as fixed accounts: a demo-only convenience, never anything real. It
  // is checked first, so a server started with it outside demo mode says exactly why it stopped
  if (!['', '0', '1'].includes(c.OPEN_PREVIEW)) throw new Error(`OPEN_PREVIEW=${c.OPEN_PREVIEW} is not understood: set OPEN_PREVIEW=1 to open every workspace without signing in (demo mode only), or leave it unset`);
  const openPreview = c.OPEN_PREVIEW === '1';
  if (openPreview && c.BIOPTIME_MODE !== 'demo') throw new Error(`OPEN_PREVIEW=1 opens every workspace without signing in and is for demo mode only, but BIOPTIME_MODE=${c.BIOPTIME_MODE}: the server will not start. Unset OPEN_PREVIEW (or run the demo with BIOPTIME_MODE=demo).`);
  if (openPreview && c.LABSTACK_MODE === 'live') throw new Error('OPEN_PREVIEW=1 refuses LABSTACK_MODE=live: anyone with the link could book real laboratory visits. Use the stand-in laboratory (LABSTACK_MODE=standin) or unset OPEN_PREVIEW.');
  // demo mode echoes activation and reset links in responses so the demo can be driven without email; that is only ever a
  // loopback convenience, so a server reachable from other machines must say which mode it runs in
  const loopback = ['127.0.0.1', 'localhost', '::1'].includes(c.HOST);
  if (merged.BIOPTIME_MODE === undefined && !loopback) throw new Error(`HOST=${c.HOST} is reachable from other machines: set BIOPTIME_MODE explicitly (development or production; demo returns sign-in links in responses)`);
  if (c.BIOPTIME_MODE === 'demo' && !loopback) console.warn(`[config] demo mode on HOST=${c.HOST}: activation and reset links are returned in API responses; use development or production for anything shared`);
  if (isProduction) {
    const weak = ['SESSION_SECRET', 'TOKEN_SECRET', 'PAYMENT_WEBHOOK_SECRET', 'LABSTACK_WEBHOOK_VALUE'].filter((k) => String((c as Record<string, unknown>)[k]).includes('demo') || String((c as Record<string, unknown>)[k]).includes('change-me'));
    if (weak.length) throw new Error(`production refuses placeholder secrets: ${weak.join(', ')}`);
    if (c.PAYMENT_PROVIDER === 'simulator') throw new Error('production refuses the payment simulator: configure a real payment provider adapter (docs/PRODUCTION_READINESS.md §2)');
    if (c.EMAIL_PROVIDER === 'outbox') throw new Error('production refuses the email outbox: members could never receive verification or reset links (docs/PRODUCTION_READINESS.md §4)');
    if (c.LABSTACK_MODE === 'live' && !c.LABSTACK_API_KEY) throw new Error('LABSTACK_MODE=live needs LABSTACK_API_KEY');
    if (!c.PUBLIC_ORIGIN.startsWith('https://')) throw new Error('production needs an https PUBLIC_ORIGIN');
  }
  if (c.LABSTACK_MODE === 'live' && (!c.LABSTACK_API_KEY || !c.LABSTACK_WEBHOOK_VALUE || c.LABSTACK_WEBHOOK_VALUE.includes('demo'))) {
    throw new Error('LABSTACK_MODE=live refuses to start without an API key and an agreed webhook value');
  }
  const resolve = (p: string) => (p === ':memory:' || path.isAbsolute(p) ? p : path.resolve(API_ROOT, p));
  return {
    ...c,
    isDemo: c.BIOPTIME_MODE === 'demo',
    isProduction,
    corsOrigins: c.CORS_ORIGINS.split(',').map((s) => s.trim()).filter(Boolean),
    databasePath: resolve(c.DATABASE_PATH),
    reportsDir: resolve(c.REPORTS_DIR),
    assetsDir: resolve(c.ASSETS_DIR),
    privateFilesDir: resolve(c.PRIVATE_FILES_DIR),
    exerciseMediaDir: resolve(c.EXERCISE_MEDIA_DIR),
    websiteDir: resolve(c.WEBSITE_DIR),
    dashboardDir: resolve(c.DASHBOARD_DIR),
    jobsEnabled: c.JOBS_ENABLED === 'true',
    openPreview,
    googleClientIds: { ...(c.GOOGLE_SIGN_IN_WEB_CLIENT_ID ? { web: c.GOOGLE_SIGN_IN_WEB_CLIENT_ID } : {}), ...(c.GOOGLE_SIGN_IN_IOS_CLIENT_ID ? { ios: c.GOOGLE_SIGN_IN_IOS_CLIENT_ID } : {}), ...(c.GOOGLE_SIGN_IN_ANDROID_CLIENT_ID ? { android: c.GOOGLE_SIGN_IN_ANDROID_CLIENT_ID } : {}) },
    appleAudiences: [...new Set([...c.APPLE_SIGN_IN_BUNDLE_IDS.split(',').map((s) => s.trim()).filter(Boolean), ...(c.APPLE_SIGN_IN_SERVICES_ID ? [c.APPLE_SIGN_IN_SERVICES_ID] : [])])],
  };
}
